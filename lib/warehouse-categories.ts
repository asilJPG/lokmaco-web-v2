/**
 * Проверка: является ли товар внутренним полуфабрикатом кухни (ПФ / PREPARED).
 * В приходных накладных от внешних поставщиков таких товаров быть не должно.
 */
export function isPfProduct(product: { name?: string; type?: string }): boolean {
  if (!product) return true;
  if (product.type === 'PREPARED') return true;
  const n = (product.name || '').toLowerCase().trim();
  return (
    n.startsWith('пф ') ||
    n.startsWith('пф.') ||
    n.startsWith('пф-') ||
    n.startsWith('п/ф') ||
    n.startsWith('[пф]') ||
    n.startsWith('(пф)') ||
    n.includes('полуфабрикат')
  );
}

/**
 * Определение естественной категории товара по его наименованию.
 */
export function getProductNaturalCategory(product: { name?: string }): string {
  const n = (product?.name || '').toLowerCase();

  // 1. Инвентарь, посуда и техника
  if (
    /(гастро[её]мкость|сотейник|кастрюл|сковород|дуршлаг|половник|венчик|лопатка|доска |доска пластик|доска деревян|сито|щипцы|миксер|блендер|весы|мясоруб|тостер|печь|роутер|стол |стул |диван|кресло|вешалка|лампа|кашпо|термометр|темпер|чаша|блюдо|бокал|пиела|ликоб|градусник|конус|sieve|whip|frypan|pot|baking ring|mousse ring|colander)/i.test(
      n
    ) &&
    !/шоколад|торт|сырники/i.test(n)
  ) {
    return 'Инвентарь и посуда';
  }

  // 2. Хозтовары и бытовая химия
  if (
    /(моющее|гель для посуды|порошок|чистящ|мыло|fairy|wallner|белизна|тряпк|губк|швабр|ведро|дезинфек|антисептик|освежител|ватные палоч|туалетн|мусор бак|мусорны|перчатка хоз)/i.test(
      n
    )
  ) {
    return 'Хозтовары и химия';
  }

  // 3. Расходники и упаковка
  if (
    /(перчатк|салфетк|стакан|крышк|коробк|бокс|пакет|трубочк|соломк|фольг|пергамент|пленк|ланчбокс|ложка|вилка|зубочистк|бумаг|манжет|elma|bubble|kraft|крафт|вакум|одноразов)/i.test(
      n
    ) &&
    !/стеклянн|фарфор/i.test(n)
  ) {
    return 'Расходники и упаковка';
  }

  // 4. Овощи и зелень
  if (
    /(картош|картофел|помидор|томат|огур|лук|чеснок|морков|зелен|укроп|петрушк|кинз|капуст|гул карам|перец|баклажан|кабач|тыква|салат|айсберг|руккол|шпинат|мята|базилик|редис|свекл|гриб|шампиньон|халапень|маслин|оливк|горох|кукуруз|броккол)/i.test(
      n
    ) &&
    !/чипсы|соус|стиральн/i.test(n)
  ) {
    return 'Овощи и зелень';
  }

  // 5. Фрукты и ягоды
  if (
    /(яблок|банан|апельсин|лимон|лайм|киви|клубник|малин|голубик|смородин|ягод|вишн|черешн|персик|абрикос|слива|ананас|манго|маракуй|авокадо|грейпфрут|мандарин|груш|арбуз|дыня|пюре манго|пюре клубник|пюре имбир|пюре малин)/i.test(
      n
    ) &&
    !/мыло|средство/i.test(n)
  ) {
    return 'Фрукты и ягоды';
  }

  // 6. Молочная продукция и сыры
  if (
    /(молок|сыр|сливк|шанти|творог|сгущен|сметан|йогурт|кефир|маскарпоне|моцарелл|motsarella|cremette|kremetti|страчателл|strachatella|пармезан|чеддер|сулугуни|фета|дорблю|брынза|сваля|сливочное масло|маргарин|фрима)/i.test(
      n
    )
  ) {
    return 'Молочка и сыры';
  }

  // 7. Мясо, птица и рыба
  if (
    /(мясо|говяд|баран|конин|ягненок|куриц|курин|кур |цыпл|филе|грудк|бедро|крыл|фарш|стейк|котлет|сосиск|колбас|ветчин|бекон|рыб|лосос|семг|тунец|креветк|морепродукт|кости|лахм|щечки|вырезка|ребра|дандана|пустирма)/i.test(
      n
    ) &&
    !/мясоруб|молоток для/i.test(n)
  ) {
    return 'Мясо и рыба';
  }

  // 8. Масла, соусы и специи
  if (
    /(масло|соус|майонез|кетчуп|горчиц|уксус|соль|специ|паприк|орегано|кориц|кунжут|кардамон|лаванда|ромашка|гвоздика|шафран|анис|сумах|жидкий дым|топинг|джем|сироп|монин|monin|соев|барбекю|цезарь|терияки)/i.test(
      n
    )
  ) {
    return 'Масла и соусы';
  }

  // 9. Бакалея, выпечка и десерты
  if (
    /(мук|сахар|канд|крахмал|кабартма|разрыхлител|дрожж|шоколад|какао|ванилин|тапиок|орех|фисташк|фундук|миндал|арахис|нутелл|вафл|булочк|хлеб|тартин|тост|тортиль|крупа|рис|макарон|паста|фитучини|лингвини|желатин|глазур|посыпк|асал|мед)/i.test(
      n
    )
  ) {
    return 'Бакалея и выпечка';
  }

  // 10. Напитки, чай и кофе
  if (/(чай|кофе|сок|напиток|кола|cola|fanta|фанта|sprite|спрайт|pepsi|пепси|вода|bonaqua|red bull|энергетик|морс|лимонад)/i.test(n)) {
    return 'Напитки, чай и кофе';
  }

  return 'Прочее';
}
